// rec 는 원본 시험의 metric.New 자리에 쓴다. 시각은 보지 않는다.
func rec(measurement string, tags map[string]string, fields map[string]any, _ time.Time) record {
	return record{measurement: measurement, tags: tags, fields: fields}
}

// normalize 는 원본 기대값의 int 를 파서가 내는 int64 로 맞춘다.
func normalize(fields map[string]any) map[string]any {
	out := make(map[string]any, len(fields))
	for k, v := range fields {
		if i, ok := v.(int); ok {
			v = int64(i)
		}
		out[k] = v
	}
	return out
}

